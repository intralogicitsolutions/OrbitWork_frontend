class UserModel {
  final String userId;
  final String name;
  final String email;
  final String timeZone;
  final String city;
  final String state;
  final String pinCode;
  final String country;
  final String phone;

  UserModel({
    required this.userId,
    required this.name,
    required this.email,
    required this.timeZone,
    required this.city,
    required this.state,
    required this.pinCode,
    required this.country,
    required this.phone,
});
}