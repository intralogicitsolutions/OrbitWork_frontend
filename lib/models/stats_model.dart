class StatsModel {
  final double earnings;
  final int jobSuccessScore;
  final int profileViews;
  final String lastUpdated;
  final int proposalsSent;
  final int proposalsViewed;
  final int interviews;
  final int hires;
  final double clientRelationshipScore;
  final int connectsLeft;
  final bool isTopRated;

  StatsModel({
    required this.earnings,
    required this.jobSuccessScore,
    required this.profileViews,
    required this.lastUpdated,
    required this.proposalsSent,
    required this.proposalsViewed,
    required this.interviews,
    required this.hires,
    required this.clientRelationshipScore,
    required this.connectsLeft,
    required this.isTopRated,
  });
}


